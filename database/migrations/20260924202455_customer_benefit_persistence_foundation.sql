-- ============================================================
-- 3. RLS — READ OWNER/ADMIN, NO DIRECT WRITES
-- ============================================================

alter table public.customer_benefits
  enable row level security;


revoke all
on table public.customer_benefits
from public, anon, authenticated;


grant select
on table public.customer_benefits
to authenticated;


drop policy if exists
  customer_benefits_owner_admin_read
on public.customer_benefits;


create policy
  customer_benefits_owner_admin_read
on public.customer_benefits
for select
to authenticated
using (
  exists (
    select 1
    from public.profiles p
    where p.id = (
      select auth.uid()
    )
      and p.authorization_status = 'ACTIVE'
      and p.role_code in (
        'OWNER',
        'ADMIN'
      )
  )
);


