-- ============================================================
-- 1. CANONICAL CUSTOMER BENEFITS TABLE
-- ============================================================

create table if not exists public.customer_benefits (
  id uuid primary key default gen_random_uuid(),

  customer_id uuid not null
    references public.customers(id)
    on delete restrict,

  benefit_code text not null,

  business_line text not null
    check (
      business_line in (
        'BEAUTY_CARE',
        'STYLE'
      )
    ),

  benefit_type text not null
    check (
      benefit_type in (
        'WELCOME',
        'RETURN_AFTER_EXPIRED',
        'PURCHASE_THRESHOLD'
      )
    ),

  discount_percent numeric(5,2) not null
    check (
      discount_percent > 0
      and discount_percent <= 100
    ),

  status text not null default 'GENERATED'
    check (
      status in (
        'GENERATED',
        'ACTIVE',
        'REDEEMED',
        'EXPIRED',
        'CANCELLED'
      )
    ),

  eligibility_reason text not null
    check (
      length(btrim(eligibility_reason)) > 0
    ),

  source_order_id uuid null
    references public.orders(id)
    on delete restrict,

  source_sale_id uuid null
    references public.sales(id)
    on delete restrict,

  redeemed_order_id uuid null
    references public.orders(id)
    on delete restrict,

  redeemed_sale_id uuid null
    references public.sales(id)
    on delete restrict,

  created_at timestamptz not null default now(),
  created_by uuid not null,

  issued_at timestamptz null,
  valid_from timestamptz null,
  valid_until timestamptz null,

  redeemed_at timestamptz null,
  cancelled_at timestamptz null,

  policy_snapshot jsonb not null
    default '{}'::jsonb,

  metadata jsonb not null
    default '{}'::jsonb,

  constraint customer_benefits_code_not_blank
    check (
      length(btrim(benefit_code)) > 0
    ),

  constraint customer_benefits_validity_order
    check (
      valid_from is null
      or valid_until is null
      or valid_until > valid_from
    ),

  constraint customer_benefits_active_temporal_state
    check (
      status <> 'ACTIVE'
      or (
        issued_at is not null
        and valid_from is not null
        and valid_until is not null
      )
    ),

  constraint customer_benefits_redeemed_state
    check (
      status <> 'REDEEMED'
      or redeemed_at is not null
    ),

  constraint customer_benefits_cancelled_state
    check (
      status <> 'CANCELLED'
      or cancelled_at is not null
    ),

  constraint customer_benefits_terminal_state_exclusive
    check (
      not (
        redeemed_at is not null
        and cancelled_at is not null
      )
    )
);


comment on table public.customer_benefits is
  'Canonical LIHEN customer benefit history. Benefits are customer-owned commercial records with immutable historical codes and no hard-delete workflow.';


comment on column public.customer_benefits.customer_id is
  'Canonical Customer Master identity. Never replace with phone or name identity.';


comment on column public.customer_benefits.benefit_code is
  'Unique customer benefit code. Final codes must be generated by a future controlled database write path, never by React.';


comment on column public.customer_benefits.policy_snapshot is
  'Snapshot of the commercial policy used when the benefit was issued so historical benefits are not reinterpreted after policy changes.';


